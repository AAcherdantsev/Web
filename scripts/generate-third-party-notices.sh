#!/usr/bin/env bash
#
# Regenerates THIRD-PARTY-NOTICES.md from the runtime dependencies of Web.Api.
# Run it after changing packages, and commit the result. Requires a completed `dotnet restore`.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROJECT="$ROOT/src/Web.Api/Web.Api.csproj"
OUTPUT="$ROOT/THIRD-PARTY-NOTICES.md"
LICENSE_TEXTS="$ROOT/scripts/licenses"
CACHE="${NUGET_PACKAGES:-$HOME/.nuget/packages}"

# Reads one element from a .nuspec file, e.g. field <copyright> file.nuspec
field() {
    grep -o "<$1>[^<]*</$1>" "$2" | head -1 | sed -E "s#</?$1>##g" || true
}

# Runtime dependency closure of the API: one "<id> <version>" pair per line
PACKAGES=$(dotnet list "$PROJECT" package --include-transitive | awk '/^ *>/ {print $2, $NF}' | sort -u)

{
    echo "# Third-party notices"
    echo
    echo "This product includes the third-party packages listed below. Each package is distributed under the"
    echo "license shown next to it. Copyright notices are reproduced from the package metadata."
    echo
    echo "Generated by \`scripts/generate-third-party-notices.sh\`. Do not edit by hand."
    echo
    echo "## Packages"
    echo
    echo "| Package | Version | License | Copyright |"
    echo "| --- | --- | --- | --- |"

    licenses_used=""
    microsoft_terms_used=0

    while read -r id ver; do
        [ -z "$id" ] && continue
        dir="$CACHE/$(echo "$id" | tr 'A-Z' 'a-z')/$ver"
        nuspec=$(ls "$dir"/*.nuspec 2>/dev/null | head -1)
        if [ -z "$nuspec" ]; then
            echo "Missing package metadata for $id $ver. Run 'dotnet restore' first." >&2
            exit 1
        fi

        license=$(grep -o '<license type="expression">[^<]*' "$nuspec" | sed 's/.*>//' | head -1 || true)
        if [ -z "$license" ]; then
            license_url=$(field licenseUrl "$nuspec")
            case "$license_url" in
                *licenses.nuget.org/*) license=${license_url##*/} ;;
                *)
                    # Licenses shipped as a file in the package, such as Microsoft Software License Terms
                    license="Microsoft Software License Terms"
                    microsoft_terms_used=1
                    ;;
            esac
        fi

        copyright=$(field copyright "$nuspec")
        [ -z "$copyright" ] && copyright="$(field authors "$nuspec") (authors)"

        echo "| $id | $ver | $license | $copyright |"

        case "$license" in
            MIT | Apache-2.0)
                case " $licenses_used " in *" $license "*) ;; *) licenses_used="$licenses_used $license" ;; esac
                ;;
        esac
    done <<< "$PACKAGES"

    echo
    echo "## License texts"
    echo

    for license in $licenses_used; do
        echo "### $license"
        echo
        echo '```text'
        cat "$LICENSE_TEXTS/$license.txt"
        echo '```'
        echo
    done

    if [ "$microsoft_terms_used" -eq 1 ]; then
        echo "### Microsoft Software License Terms"
        echo
        echo "The Microsoft.Data.SqlClient native runtime (Microsoft.Data.SqlClient.SNI.runtime) and"
        echo "Microsoft.Identity.Client.NativeInterop are distributed under the Microsoft Software License Terms."
        echo "The full terms are the \`LICENSE.txt\` file inside each package:"
        echo "https://www.nuget.org/packages/Microsoft.Data.SqlClient.SNI.runtime"
        echo
    fi
} > "$OUTPUT"

echo "Wrote $OUTPUT"
